def _tiny_shift(base: str, tiny: str):
    # Explicit-context addition: plain `Decimal(1) + Decimal("1E-45")`
    # would round the INPUT to the 28-digit ambient context and the test
    # would measure literal rounding instead of solver behavior.
    from academic_core.domain.engineering.math.trig import make_context

    return make_context().add(Decimal(base), Decimal(tiny))


