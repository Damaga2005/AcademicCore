    assert r.solution == (
        RationalComplex(Fraction(10, 9), Fraction(2, 9)),
        RationalComplex(Fraction(10, 9), Fraction(-1, 9)),
    )
    assert r.solution == cramer2(A, b)  # independent formula agrees


