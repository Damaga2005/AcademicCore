TOL = Decimal("1E-40")  # default absolute tolerance for HP comparisons


def R(re, im=0):
    return RationalComplex(Fraction(re), Fraction(im))


def C(re, im=0):
    return DecimalComplex(Decimal(str(re)), Decimal(str(im)))


def close(a: DecimalComplex, b: DecimalComplex, tol=TOL) -> bool:
    from academic_core.domain.engineering.math.trig import make_context

    ctx = make_context()
    d = a - b
    return ctx.sqrt(d.squared_modulus()) <= tol


def close_list(xs, ys, tol=TOL) -> bool:
    return len(xs) == len(ys) and all(close(x, y, tol) for x, y in zip(xs, ys))


def cramer2(A, b):
    """Independent 2x2 reference via Cramer's rule (no elimination)."""
    a, bb = A[0][0], A[0][1]
    c, d = A[1][0], A[1][1]
    e, f = b[0], b[1]
    det = a * d - bb * c
    assert not det.is_zero_exact()
    return ((e * d - bb * f) / det, (a * f - e * c) / det)


def det3(M):
    """Independent 3x3 determinant via the Rule of Sarrus (no elimination)."""
    a, b, c = M[0]
    d, e, f = M[1]
    g, h, i = M[2]
    return a * e * i + b * f * g + c * d * h - c * e * g - b * d * i - a * f * h


def cramer3(A, b):
    """Independent 3x3 reference via Cramer's rule (no elimination)."""
    det = det3(A)
    assert not det.is_zero_exact()
    cols = list(zip(*A))
    out = []
    for k in range(3):
        Mk = [list(r) for r in zip(*cols)]
        for r in range(3):
            Mk[r][k] = b[r]
        out.append(det3(Mk) / det)
    return tuple(out)


