def test_metamorphic_conjugation_both_modes():
    # det = (1+j)(3+j) - 2*(2j) = 2 (nonsingular by hand).
    A = [[R(1, 1), R(2)], [R(0, 2), R(3, 1)]]
    b = [R(1, 2), R(2)]
    p = ComplexLinearProblem.from_sequences(A, b)
