    assert r.status == SolveStatus.SOLVED
    rc = solve(conjugate_system(p), NumericMode.EXACT)
    assert r.status == rc.status == SolveStatus.SOLVED
    assert rc.solution == tuple(e.conjugate() for e in r.solution)
    Ah = [[C(1, 1), C(2)], [C(0, 2), C(3, 1)]]
    bh = [C(1, 2), C(2)]
